/* 1) Cabecalho da OC criada (procura pela chave de integracao) */
SELECT
     TMOV.IDMOV
    ,TMOV.NUMEROMOV
    ,TMOV.SERIE
    ,TMOV.CODTMV
    ,TMOV.STATUS
    ,TMOV.DATAEMISSAO
    ,TMOV.CODCFO
    ,FCFO.NOMEFANTASIA AS FORNECEDOR
    ,TMOV.CODCPG
    ,TMOV.CODCCUSTO
    ,TMOV.VALORBRUTO
    ,TMOV.VALORLIQUIDO
    ,TMOV.IDINTEGRACAO
    ,TMOV.SEGUNDONUMERO
    ,TMOV.USUARIOCRIACAO
    ,TMOV.DATACRIACAO
FROM TMOV
INNER JOIN FCFO
        ON FCFO.CODCOLIGADA = TMOV.CODCOLCFO
       AND FCFO.CODCFO      = TMOV.CODCFO
WHERE TMOV.CODCOLIGADA  = 1
  AND TMOV.CODTMV       = '1.1.04'
  AND TMOV.IDINTEGRACAO LIKE 'SOFTEXPERT-TESTE-%';

/* 2) Itens */
SELECT
     TITMMOV.IDMOV
    ,TITMMOV.NSEQITMMOV
    ,TPRODUTO.CODIGOPRD
    ,TPRODUTO.NOMEFANTASIA AS PRODUTO
    ,TITMMOV.QUANTIDADE
    ,TITMMOV.PRECOUNITARIO
    ,TITMMOV.VALORLIQUIDO
    ,TITMMOV.CODUND
    ,TITMMOV.CODCCUSTO
    ,TITMMOV.CAMPOLIVRE
FROM TITMMOV
INNER JOIN TMOV
        ON TMOV.CODCOLIGADA = TITMMOV.CODCOLIGADA
       AND TMOV.IDMOV       = TITMMOV.IDMOV
INNER JOIN TPRODUTO
        ON TPRODUTO.CODCOLPRD = TITMMOV.CODCOLIGADA
       AND TPRODUTO.IDPRD     = TITMMOV.IDPRD
WHERE TMOV.CODCOLIGADA  = 1
  AND TMOV.IDINTEGRACAO LIKE 'SOFTEXPERT-TESTE-%'
ORDER BY TITMMOV.IDMOV, TITMMOV.NSEQITMMOV;

/* 3) Rateio do cabecalho: a soma tem que bater com TMOV.VALORLIQUIDO */
SELECT
     TMOVRATCCU.IDMOV
    ,TMOVRATCCU.CODCCUSTO
    ,TMOVRATCCU.VALOR
FROM TMOVRATCCU
INNER JOIN TMOV
        ON TMOV.CODCOLIGADA = TMOVRATCCU.CODCOLIGADA
       AND TMOV.IDMOV       = TMOVRATCCU.IDMOV
WHERE TMOV.CODCOLIGADA  = 1
  AND TMOV.IDINTEGRACAO LIKE 'SOFTEXPERT-TESTE-%';

/* 4) Anti-duplicidade: o programa deve rodar isto ANTES de cada SaveRecord.
      Se retornar linha, a OC ja foi criada -> nao enviar de novo. */
SELECT
     TMOV.IDMOV
    ,TMOV.NUMEROMOV
FROM TMOV
WHERE TMOV.CODCOLIGADA  = 1
  AND TMOV.CODTMV       = '1.1.04'
  AND TMOV.IDINTEGRACAO = 'SOFTEXPERT-TESTE-0001';
